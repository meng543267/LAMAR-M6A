#!/usr/bin/env python
"""Fine-tune LAMAR-m6A sequence classification models.

This is the cleaned GitHub version of the original single-run fine-tuning
script. It reads HuggingFace datasets generated by build_tokenized_dataset.py:

    dataset/full/m6a_full_{cell}_{length}/
    dataset/mature/m6a_mature_{cell}_{length}/

and writes checkpoints plus validation metrics under outputs/.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import json
from pathlib import Path

import numpy as np


DEFAULT_CELL_LINES = ["a549", "cd8t", "hek293", "hela", "molm13"]
DEFAULT_LENGTHS = [51, 101, 201, 401, 801, 1601]


def import_object(import_path: str):
    """Import an object from 'module.submodule:ObjectName'."""
    module_name, object_name = import_path.split(":", 1)
    module = importlib.import_module(module_name)
    return getattr(module, object_name)


def dataset_path(dataset_dir: Path, mode: str, cell: str, length: int) -> Path:
    return dataset_dir / mode / f"m6a_{mode}_{cell}_{length}"


def resolve_split(data, requested: str, role: str, fallbacks: list[str] | None = None) -> str:
    """Return an available split name, with compatibility fallback for old datasets."""
    if requested in data:
        return requested

    fallbacks = fallbacks or []
    for split in fallbacks:
        if split in data:
            print(
                f"Warning: requested {role} split '{requested}' was not found. "
                f"Using '{split}' instead. Available splits: {list(data.keys())}"
            )
            return split

    raise KeyError(
        f"{role} split '{requested}' not found. "
        f"Available splits: {list(data.keys())}. "
        "Either set --eval-split to an existing split or rebuild the tokenized dataset with a valid split."
    )


def default_output_dir(base: Path, mode: str, cell: str, length: int, batch_size: int, accum_steps: int) -> Path:
    return base / "checkpoints" / mode / f"{cell}-{length}-bs{batch_size}-acc{accum_steps}"


def stable_softmax(logits: np.ndarray) -> np.ndarray:
    probs = np.exp(logits - np.max(logits, axis=1, keepdims=True))
    return probs / np.sum(probs, axis=1, keepdims=True)


def compute_metrics(eval_pred):
    from sklearn.metrics import (
        accuracy_score,
        auc,
        confusion_matrix,
        f1_score,
        matthews_corrcoef,
        precision_recall_curve,
        precision_score,
        recall_score,
        roc_auc_score,
    )

    predictions, labels = eval_pred
    labels = np.asarray(labels).flatten()
    probs_all = stable_softmax(np.asarray(predictions))
    probs = probs_all[:, 1]
    preds = np.argmax(probs_all, axis=1).flatten()

    accuracy = accuracy_score(labels, preds)
    precision = precision_score(labels, preds, zero_division=0)
    recall = recall_score(labels, preds, zero_division=0)
    f1 = f1_score(labels, preds, zero_division=0)
    mcc = matthews_corrcoef(labels, preds)

    if len(set(labels.tolist())) == 2:
        roc_auc = roc_auc_score(labels, probs)
        precision_curve, recall_curve, _ = precision_recall_curve(labels, probs)
        pr_auc = auc(recall_curve, precision_curve)
        tn, fp, fn, tp = confusion_matrix(labels, preds, labels=[0, 1]).ravel()
        specificity = tn / (tn + fp) if (tn + fp) > 0 else 0.0
    else:
        roc_auc = float("nan")
        pr_auc = float("nan")
        specificity = float("nan")

    return {
        "accuracy": float(accuracy),
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "roc_auc": float(roc_auc),
        "pr_auc": float(pr_auc),
        "specificity": float(specificity),
        "mcc": float(mcc),
    }


def load_pretrained_weights(model, state_path: Path | None) -> None:
    if state_path is None:
        print("No pretraining state is loaded.")
        return

    import torch

    print(f"Loading pretraining parameters: {state_path}")
    if str(state_path).endswith(".bin"):
        model.load_state_dict(torch.load(state_path, map_location="cpu"), strict=False)
    elif str(state_path).endswith(".safetensors"):
        from safetensors.torch import load_model

        load_model(model, filename=str(state_path), strict=False)
    else:
        raise ValueError(f"Unsupported pretraining state format: {state_path}")


def make_training_arguments(args, output_dir: Path):
    from transformers import TrainingArguments

    kwargs = dict(
        disable_tqdm=False,
        dataloader_drop_last=args.dataloader_drop_last,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.eval_batch_size or args.batch_size,
        learning_rate=args.learning_rate,
        weight_decay=args.weight_decay,
        adam_beta1=args.adam_beta1,
        adam_beta2=args.adam_beta2,
        adam_epsilon=args.adam_epsilon,
        warmup_ratio=args.warmup_ratio,
        num_train_epochs=args.epochs,
        max_grad_norm=args.max_grad_norm,
        gradient_accumulation_steps=args.gradient_accumulation_steps,
        output_dir=str(output_dir),
        eval_steps=args.eval_steps,
        save_steps=args.save_steps,
        logging_steps=args.logging_steps,
        save_strategy="steps",
        logging_strategy="steps",
        fp16=args.fp16,
        report_to=args.report_to,
        save_total_limit=args.save_total_limit,
        load_best_model_at_end=args.load_best_model_at_end,
        metric_for_best_model=args.metric_for_best_model,
        greater_is_better=True,
    )

    signature = inspect.signature(TrainingArguments.__init__)
    if "eval_strategy" in signature.parameters:
        kwargs["eval_strategy"] = "steps"
    else:
        kwargs["evaluation_strategy"] = "steps"
    return TrainingArguments(**kwargs)


def build_model(args, tokenizer):
    from transformers import AutoConfig

    model_cls = import_object(args.model_class)
    config = AutoConfig.from_pretrained(
        args.model_config,
        vocab_size=len(tokenizer),
        pad_token_id=tokenizer.pad_token_id,
        mask_token_id=tokenizer.mask_token_id,
        num_labels=args.num_labels,
        token_dropout=args.token_dropout,
        positional_embedding_type=args.positional_embedding_type,
        hidden_size=args.hidden_size,
        intermediate_size=args.intermediate_size,
        num_attention_heads=args.num_attention_heads,
        num_hidden_layers=args.num_hidden_layers,
    )

    model = model_cls(
        config,
        head_type=args.head_type,
        freeze=args.freeze,
        kernel_sizes=args.kernel_sizes,
        ocs=args.ocs,
    )

    if args.flash_attention:
        flash_cls = import_object(args.flash_attention_class)
        for i in range(config.num_hidden_layers):
            model.esm.encoder.layer[i].attention.self = flash_cls(
                config,
                position_embedding_type=args.positional_embedding_type,
            )

    load_pretrained_weights(model, args.pretrain_state_path)
    return model


def run_one(args, mode: str, cell: str, length: int) -> None:
    from datasets import load_from_disk
    from transformers import AutoTokenizer, DataCollatorWithPadding, Trainer

    data_path = args.data_path or dataset_path(args.dataset_dir, mode, cell, length)
    if not data_path.exists():
        raise FileNotFoundError(f"Dataset not found: {data_path}")

    model_max_length = args.model_max_length or length + 2
    output_dir = args.output_dir or default_output_dir(
        args.outputs_dir,
        mode,
        cell,
        length,
        args.batch_size,
        args.gradient_accumulation_steps,
    )

    tokenizer = AutoTokenizer.from_pretrained(
        args.tokenizer_path,
        model_max_length=model_max_length,
    )
    data = load_from_disk(data_path)
    data_collator = DataCollatorWithPadding(tokenizer=tokenizer, padding=True)
    model = build_model(args, tokenizer)
    train_args = make_training_arguments(args, output_dir)

    train_split = resolve_split(data, args.train_split, "train")
    eval_split = resolve_split(data, args.eval_split, "eval", fallbacks=["validation", "test"])

    trainer = Trainer(
        model=model,
        args=train_args,
        train_dataset=data[train_split],
        eval_dataset=data[eval_split],
        compute_metrics=compute_metrics,
        data_collator=data_collator,
        tokenizer=tokenizer,
    )

    trainer.train(resume_from_checkpoint=args.resume_from_checkpoint)
    trainer.save_model(output_dir / "final_model")

    metrics_dir = args.outputs_dir / "metrics" / mode
    metrics_dir.mkdir(parents=True, exist_ok=True)

    eval_metrics = trainer.evaluate(data[eval_split])
    (metrics_dir / f"{cell}_{length}_{eval_split}.json").write_text(
        json.dumps(eval_metrics, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print(f"saved validation metrics: {metrics_dir / f'{cell}_{length}_{eval_split}.json'}")


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["full", "mature"], default="full")
    parser.add_argument("--cell", choices=DEFAULT_CELL_LINES, default="hek293")
    parser.add_argument("--length", type=int, choices=DEFAULT_LENGTHS, default=801)
    parser.add_argument("--dataset-dir", type=Path, default=Path("dataset"))
    parser.add_argument("--data-path", type=Path, default=None, help="Override tokenized dataset path.")
    parser.add_argument("--outputs-dir", type=Path, default=Path("outputs"))
    parser.add_argument("--output-dir", type=Path, default=None, help="Override checkpoint output directory.")
    parser.add_argument("--tokenizer-path", type=Path, default=Path("tokenizer/single_nucleotide"))
    parser.add_argument("--model-config", type=Path, default=Path("config/config_150M.json"))
    parser.add_argument("--pretrain-state-path", type=Path, default=Path("src/pretrain/model.safetensors"))
    parser.add_argument("--model-class", default="scripts.sequence_classification_patch:EsmForSequenceClassification")
    parser.add_argument("--flash-attention-class", default="flash_attn_patch:EsmSelfAttentionAddFlashAttnPatch")

    parser.add_argument("--model-max-length", type=int, default=None)
    parser.add_argument("--num-labels", type=int, default=2)
    parser.add_argument("--token-dropout", action="store_true")
    parser.add_argument("--positional-embedding-type", default="rotary")
    parser.add_argument("--hidden-size", type=int, default=768)
    parser.add_argument("--intermediate-size", type=int, default=3072)
    parser.add_argument("--num-attention-heads", type=int, default=12)
    parser.add_argument("--num-hidden-layers", type=int, default=12)
    parser.add_argument("--head-type", default="Linear")
    parser.add_argument("--freeze", action="store_true")
    parser.add_argument("--kernel-sizes", nargs="+", type=int, default=[2, 3, 5])
    parser.add_argument("--ocs", type=int, default=32)
    parser.add_argument("--flash-attention", action="store_true")

    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--eval-batch-size", type=int, default=None)
    parser.add_argument("--gradient-accumulation-steps", type=int, default=4)
    parser.add_argument("--learning-rate", type=float, default=1e-5)
    parser.add_argument("--warmup-ratio", type=float, default=0.05)
    parser.add_argument("--epochs", type=float, default=2)
    parser.add_argument("--max-grad-norm", type=float, default=1.0)
    parser.add_argument("--weight-decay", type=float, default=0.01)
    parser.add_argument("--adam-beta1", type=float, default=0.9)
    parser.add_argument("--adam-beta2", type=float, default=0.98)
    parser.add_argument("--adam-epsilon", type=float, default=1e-8)
    parser.add_argument("--eval-steps", type=int, default=100)
    parser.add_argument("--save-steps", type=int, default=100)
    parser.add_argument("--logging-steps", type=int, default=100)
    parser.add_argument("--save-total-limit", type=int, default=3)
    parser.add_argument("--load-best-model-at-end", action=argparse.BooleanOptionalAction, default=False)
    parser.add_argument("--metric-for-best-model", default="pr_auc")
    parser.add_argument("--dataloader-drop-last", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--fp16", action="store_true")
    parser.add_argument("--report-to", default="none")
    parser.add_argument("--resume-from-checkpoint", default=None)

    parser.add_argument("--train-split", default="train")
    parser.add_argument("--eval-split", default="test")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    run_one(args, args.mode, args.cell, args.length)


if __name__ == "__main__":
    main()
